-- Tipos admitidos en el maestro de productos.
ALTER TABLE productos
  ADD CONSTRAINT ck_productos_tipo
  CHECK (tipo IN ('INSUMO', 'ELABORADO', 'REVENTA'));

-- Completar generación automática de identificadores que faltaba en estas tablas.
ALTER TABLE productos_venta
  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE historial_precios_venta
  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Recargo individual y costo de referencia revisado por producto elaborado.
ALTER TABLE productos_venta
  ADD COLUMN recargo_porcentaje numeric(8,2) NULL,
  ADD COLUMN costo_referencia numeric(14,4) NULL,
  ADD CONSTRAINT ck_productos_venta_recargo
    CHECK (recargo_porcentaje IS NULL OR recargo_porcentaje >= 0),
  ADD CONSTRAINT ck_productos_venta_costo_referencia
    CHECK (costo_referencia IS NULL OR costo_referencia >= 0);

-- Parámetro general utilizado como valor inicial para nuevos elaborados.
CREATE TABLE configuracion_comercial (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  recargo_predeterminado_elaborados numeric(8,2) NOT NULL DEFAULT 100
    CHECK (recargo_predeterminado_elaborados >= 0),
  fecha_actualizacion timestamptz NOT NULL DEFAULT now()
);

INSERT INTO configuracion_comercial (id, recargo_predeterminado_elaborados)
VALUES (1, 100)
ON CONFLICT (id) DO NOTHING;
